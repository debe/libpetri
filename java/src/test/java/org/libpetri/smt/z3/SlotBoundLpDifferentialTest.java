    private static final Place<Integer> SOURCE = Place.of("source", Integer.class);
    private static final Place<Integer> BUDGET = Place.of("budget", Integer.class);
    private static final Place<Integer> PENDING = Place.of("pending", Integer.class);
    private static final Place<String> BRANCH_A = Place.of("branchA", String.class);
    private static final Place<String> BRANCH_B = Place.of("branchB", String.class);
    private static final Place<String> MERGED = Place.of("merged", String.class);
    private static final Place<String> ARCHIVED = Place.of("archived", String.class);

    /** The scatter-gather &nu;-net, with {@code archive: merged -> archived} when asked. */
    private static PetriNet scatterGather(boolean archive) {
        var fork = Transition.builder("fork")
            .inputs(In.one(SOURCE), In.one(BUDGET))
            .outputs(Out.and(BRANCH_A, BRANCH_B, PENDING))
            .build();
        var join = Transition.builder("join")
            .inputs(In.one(BRANCH_A), In.one(BRANCH_B), In.one(PENDING))
            .match(MatchSpec.builder()
                .key(BRANCH_A, (String s) -> NameId.of(s))
                .key(BRANCH_B, (String s) -> NameId.of(s))
                .build())
            .outputs(Out.and(MERGED, BUDGET))
            .build();
        var b = PetriNet.builder(archive ? "scatter_gather_archive" : "scatter_gather").transitions(fork, join);
        if (archive) {
            b.transition(Transition.builder("archive").inputs(In.one(MERGED)).outputs(Out.place(ARCHIVED)).build());
        }
        return b.build();
    }

    private static MarkingState scatterGatherMarking() {
        return MarkingState.builder().tokens(SOURCE, 3).tokens(BUDGET, 2).build();
    }

    private record Planned(NameColouredEncoder.ColouredPlan plan, SlotBound reported, FlatNet flat) {}

    /** {@code buildPlan} with the simplex replaced by {@code answer}, and the bound it reported. */
    private static Planned planWith(PetriNet net, MarkingState initial, Function<FlatNet, LpAnswer> answer) {
        var flat = NetFlattener.flatten(net, Set.of(), EnvironmentAnalysisMode.ignore());
        var mints = NameFragment.declaredMints(net, Set.of("budget"), Set.of());
        var reported = new SlotBound[1];
        var plan = NameColouredEncoder.buildPlan(net, flat, initial, mints, FragmentMode.BASE, Set.of(),
            _ -> answer.apply(flat), b -> reported[0] = b);
        assertNotNull(reported[0], "the sink is called once the plan reaches the bound");
        return new Planned(plan, reported[0], flat);
    }

    /** Weights by place name, every other place 0. */
    private static LpAnswer weights(FlatNet flat, Map<String, Long> byName, long d) {
        var w = new ArrayList<BigInteger>();
        for (int p = 0; p < flat.placeCount(); p++) {
            w.add(BigInteger.valueOf(byName.getOrDefault(flat.places().get(p).name(), 0L)));
        }
        return new LpAnswer.Optimal(new ScaledCover(w, BigInteger.valueOf(d)), 5, 2);
    }

    private static Map<String, Long> w(Object... pairs) {
        var m = new LinkedHashMap<String, Long>();
        for (int i = 0; i < pairs.length; i += 2) {
            m.put((String) pairs[i], ((Number) pairs[i + 1]).longValue());
        }
        return m;
    }

    @Test
    void buildPlanTakesKOnlyFromAWeightingTheReCheckAccepts() {
        var net = scatterGather(true);
        var m0 = scatterGatherMarking();

        var lp = planWith(net, m0, flat -> SlotBoundLp.solve(flat, m0, SlotLpFixtures.indices(flat, "branchA", "branchB")));
        assertNotNull(lp.plan(), String.valueOf(lp.reported()));
        assertEquals(4, lp.plan().k());

        record Refused(Map<String, Long> weights, long d, String reason) {}
        var optimal = w("branchA", 1, "branchB", 1, "budget", 2);
        var withArchived = new LinkedHashMap<>(optimal);
        withArchived.put("archived", 1L);
        for (var r : List.of(
                new Refused(w("branchA", 1, "branchB", 1, "budget", 2, "pending", -1), 1,
                    "place 'pending' has negative weight -1"),
                new Refused(w("branchA", 2, "branchB", 1, "budget", 6), 2,
                    "coloured place 'branchB' has weight 1 below the denominator 2"),
                new Refused(withArchived, 1, "transition 'archive' increases the weighted sum by 1"),
                new Refused(optimal, 0, "denominator 0 is not positive"),
                new Refused(optimal, -1, "denominator -1 is not positive"),
                new Refused(w("branchA", 1, "branchB", 1, "budget", 2, "source", 1L << 31), 1,
                    "k=6442450948 exceeds 2147483647"))) {
            var p = planWith(net, m0, flat -> weights(flat, r.weights(), r.d()));
            assertNull(p.plan(), r.reason());
            assertEquals(new SlotBound.CheckFailed(r.reason()), p.reported());
            assertEquals("  Colour-slot bound: none (LP weighting failed the exact re-check: " + r.reason() + ")",
                p.reported().reportLine());
        }

        // A feasible weighting that is not optimal is accepted, with its larger k.
        var loose = planWith(net, m0, flat -> weights(flat, w("branchA", 1, "branchB", 1, "budget", 2, "source", 1), 1));
        assertNotNull(loose.plan(), String.valueOf(loose.reported()));
        assertEquals(7, loose.plan().k());
        // Every answer without a weighting refuses the plan.
        for (var answer : List.<LpAnswer>of(new LpAnswer.Infeasible(5, 2), new LpAnswer.PivotLimit(350),
                new LpAnswer.Stopped())) {
            assertNull(planWith(net, m0, _ -> answer).plan(), String.valueOf(answer));
        }
    }

