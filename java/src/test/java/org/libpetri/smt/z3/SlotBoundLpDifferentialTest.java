    /**
     * On the scatter-gather fixture (the shared coloured net whose {@code k} changed, 10 to 4), the
     * coloured encoding answers every query the same with the LP's {@code k} as with the old
     * semiflow weighting's, fed to {@code buildPlan} through its {@code lp} function. Spacer may
     * run out of time on the larger encoding ({@code unknown}); it must never answer the other way.
     */
    @Test
    @EnabledIf("z3Available")
    void theLpKAndTheSemiflowKGiveTheSameVerdicts() throws Exception {
        var net = scatterGather(false);
        var m0 = scatterGatherMarking();
        var flat = NetFlattener.flatten(net, Set.of(), EnvironmentAnalysisMode.ignore());
        int[] coloured = SlotLpFixtures.indices(flat, "branchA", "branchB");
        long[] old = OldSlotBound.colourSlotWeighting(flat.placeCount(), coloured,
            OldSlotBound.validatedSemiflows(flat, m0));
        assertNotNull(old, "the scatter-gather net has a covering semiflow");
        var oldAnswer = new LpAnswer.Optimal(new ScaledCover(
            Arrays.stream(old).mapToObj(BigInteger::valueOf).toList(), BigInteger.ONE), 0, 0);
        var oldPlan = planWith(net, m0, _ -> oldAnswer).plan();
        var lpPlan = planWith(net, m0, f -> SlotBoundLp.solve(f, m0, coloured)).plan();
        assertNotNull(oldPlan, "old plan");
        assertNotNull(lpPlan, "LP plan");
        assertEquals(List.of(10, 4), List.of(oldPlan.k(), lpPlan.k()));
        record Query(SmtProperty property, String expected) {}
        int decided = 0;
        for (var query : List.of(
                new Query(SmtProperty.placeBound(BUDGET, 2), "sat"),
                new Query(SmtProperty.placeBound(BRANCH_A, 2), "sat"),
                new Query(SmtProperty.placeBound(BRANCH_A, 1), "unsat"),
                new Query(SmtProperty.placeBound(MERGED, 2), "unsat"),
                new Query(SmtProperty.placeBound(PENDING, 2), "sat"))) {
            var answers = new ArrayList<String>();
            for (var plan : List.of(oldPlan, lpPlan)) {
                var enc = NameColouredEncoder.encode(plan, flat, m0, query.property(), List.of(), Set.of());
                assertNotNull(enc, "encodes");
                long start = System.nanoTime();
                answers.add(spacer(enc.smt2()));
                System.out.println("[slot-bound LP] k=" + plan.k() + " " + query.property() + ": "
                    + answers.getLast() + " in " + (System.nanoTime() - start) / 1_000_000 + " ms");
            }
            assertEquals(query.expected(), answers.get(1), "LP k: " + query.property());
            assertTrue(answers.get(0).equals(query.expected()) || answers.get(0).equals("unknown"),
                "old k: " + query.property() + " " + answers);
            if (answers.get(0).equals(query.expected())) {
                decided++;
            }
        }
        assertTrue(decided >= 3, "the old k decided only " + decided + " queries");
    }

