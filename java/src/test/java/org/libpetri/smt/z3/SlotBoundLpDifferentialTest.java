    /** xorshift64*, as in the Rust suite, so both languages draw the same nets. */
    private static final class Rng {
        private long state;

        Rng(long state) {
            this.state = state;
        }

        long next() {
            state ^= state >>> 12;
            state ^= state << 25;
            state ^= state >>> 27;
            return state * 0x2545_F491_4F6C_DD1DL;
        }

        int below(long n) {
            return (int) Long.remainderUnsigned(next(), n);
        }

        boolean chance(long percent) {
            return below(100) < percent;
        }
    }

    /**
     * A seeded small &nu;-like flat net: two keys (sometimes a third coloured carrier), a budget,
     * a few uncoloured places, mints into the keys, joins out of them, a coloured drain now and
     * then, and uncoloured rows, some with a reset or consume-all arc on an uncoloured place.
     * Coloured places start empty.
     */
    static Subject randomSubject(long seed) {
        var rng = new Rng((seed * 0x9E37_79B9_7F4A_7C15L) | 1);
        boolean carrier = rng.chance(30);
        int extra = 1 + rng.below(3);
        var names = new ArrayList<>(List.of("a", "b", "budget"));
        if (carrier) {
            names.add("c");
        }
        for (int i = 0; i < extra; i++) {
            names.add("u" + i);
        }
        names.sort(null);
        int n = names.size();
        Function<String, Integer> idx = names::indexOf;
        int[] keys = carrier ? new int[] {idx.apply("a"), idx.apply("b"), idx.apply("c")}
            : new int[] {idx.apply("a"), idx.apply("b")};
        int carrierPlace = carrier ? idx.apply("c") : -1;
        var unc = new ArrayList<Integer>();
        for (int p = 0; p < n; p++) {
            final int q = p;
            if (Arrays.stream(keys).noneMatch(k -> k == q)) {
                unc.add(p);
            }
        }
        var rows = new ArrayList<Row>();
        int budget = idx.apply("budget");
        int mints = 1 + rng.below(2);
        for (int m = 0; m < mints; m++) {
            int[] pre = new int[n];
            int[] post = new int[n];
            pre[budget] = 1 + rng.below(3);
            if (rng.chance(30)) {
                pre[unc.get(rng.below(unc.size()))] += 1;
            }
            for (int k : keys) {
                if (rng.chance(85) || k == idx.apply("a")) {
                    post[k] = 1;
                }
            }
            if (rng.chance(30)) {
                post[unc.get(rng.below(unc.size()))] += 1;
            }
            rows.add(row(names, "mint" + m, pre, post, List.of(), List.of()));
        }
        int joins = 1 + rng.below(2);
        for (int j = 0; j < joins; j++) {
            int[] pre = new int[n];
            int[] post = new int[n];
            for (int k : keys) {
                if (k != carrierPlace || rng.chance(50)) {
                    pre[k] = 1;
                }
            }
            post[budget] = rng.below(3);
            if (rng.chance(50)) {
                post[unc.get(rng.below(unc.size()))] += 1;
            }
            rows.add(row(names, "join" + j, pre, post, List.of(), List.of()));
        }
        if (rng.chance(30)) {
            int[] pre = new int[n];
            int[] post = new int[n];
            pre[keys[rng.below(keys.length)]] = 1;
            post[unc.get(rng.below(unc.size()))] = 1;
            rows.add(row(names, "drain", pre, post, List.of(), List.of()));
        }
        int sides = rng.below(4);
        for (int t = 0; t < sides; t++) {
            int[] pre = new int[n];
            int[] post = new int[n];
            int from = unc.get(rng.below(unc.size()));
            int to = unc.get(rng.below(unc.size()));
            pre[from] = 1 + rng.below(2);
            post[to] += 1 + rng.below(2);
            var reset = new ArrayList<Integer>();
            var all = new ArrayList<Integer>();
            int side = unc.get(rng.below(unc.size()));
            int choice = rng.below(6);
            if (choice == 0 && side != from) {
                reset.add(side);
            } else if (choice == 1) {
                pre[from] = 1;
                all.add(from);
            }
            rows.add(row(names, "side" + t, pre, post, reset, all));
        }
        var tokens = new LinkedHashMap<String, Integer>();
        tokens.put("budget", rng.below(4));
        for (int u : unc) {
            if (!names.get(u).equals("budget") && rng.chance(40)) {
                tokens.put(names.get(u), 1 + rng.below(2));
            }
        }
        FlatNet flat = SlotLpFixtures.flat(names, rows);
        return new Subject("random-" + seed, flat, SlotLpFixtures.marking(flat, tokens), keys.clone());
    }

    private static Row row(List<String> names, String name, int[] pre, int[] post, List<Integer> reset,
                           List<Integer> all) {
        Map<String, Integer> preM = new LinkedHashMap<>();
        Map<String, Integer> postM = new LinkedHashMap<>();
        for (int p = 0; p < names.size(); p++) {
            if (pre[p] != 0) {
                preM.put(names.get(p), pre[p]);
            }
            if (post[p] != 0) {
                postM.put(names.get(p), post[p]);
            }
        }
        Set<String> resetS = new HashSet<>();
        reset.forEach(p -> resetS.add(names.get(p)));
        Set<String> allS = new HashSet<>();
        all.forEach(p -> allS.add(names.get(p)));
        return new Row(name, preM, postM, resetS, allS);
    }

